def translate(seq):
    # Standard RNA codon table
    codon_table = {
        'UUU': 'F', 'UUC': 'F', 'UUA': 'L', 'UUG': 'L',
        'UCU': 'S', 'UCC': 'S', 'UCA': 'S', 'UCG': 'S',
        'UAU': 'Y', 'UAC': 'Y', 'UAA': '*', 'UAG': '*',
        'UGU': 'C', 'UGC': 'C', 'UGA': '*', 'UGG': 'W',

        'CUU': 'L', 'CUC': 'L', 'CUA': 'L', 'CUG': 'L',
        'CCU': 'P', 'CCC': 'P', 'CCA': 'P', 'CCG': 'P',
        'CAU': 'H', 'CAC': 'H', 'CAA': 'Q', 'CAG': 'Q',
        'CGU': 'R', 'CGC': 'R', 'CGA': 'R', 'CGG': 'R',

        'AUU': 'I', 'AUC': 'I', 'AUA': 'I', 'AUG': 'M',
        'ACU': 'T', 'ACC': 'T', 'ACA': 'T', 'ACG': 'T',
        'AAU': 'N', 'AAC': 'N', 'AAA': 'K', 'AAG': 'K',
        'AGU': 'S', 'AGC': 'S', 'AGA': 'R', 'AGG': 'R',

        'GUU': 'V', 'GUC': 'V', 'GUA': 'V', 'GUG': 'V',
        'GCU': 'A', 'GCC': 'A', 'GCA': 'A', 'GCG': 'A',
        'GAU': 'D', 'GAC': 'D', 'GAA': 'E', 'GAG': 'E',
        'GGU': 'G', 'GGC': 'G', 'GGA': 'G', 'GGG': 'G'
    }

    # Convert DNA to RNA
    seq = seq.upper().replace('T', 'U')

    # Initialize an empty list for the protein sequence
    protein = []

    # Read the sequence in groups of three
    for i in range(0, len(seq) - 2, 3):
        codon = seq[i:i+3]

        # Translate each codon
        amino_acid = codon_table.get(codon, 'X')

        # Stop translation at a stop codon
        if amino_acid == '*':
            break

        protein.append(amino_acid)

    # Return the protein sequence
    return ''.join(protein)


# Test the function
dna_sequence = "ATGGCTTTTGAATAA"

protein_sequence = translate(dna_sequence)

print("DNA sequence:", dna_sequence)
print("Protein sequence:", protein_sequence)

# Check the expected answer
assert protein_sequence == "MAFE"

print("Test passed!")